#pragma once

// ============================================================================
//  ВСЕ настраиваемые параметры грани «Календарь» — в этом файле.
//
//  После правки:   ./scripts/overlay.sh && ./scripts/build.sh && ./scripts/flash.sh
//  Особые случаи (помечены ⚠ ниже):
//    • kCalendarFirstFace — читает хук: после смены нужен ./scripts/sync.sh (чистый клон);
//    • k*FontPt          — читает генератор: после смены запустить ./tools/gen_digit_fonts.sh
//                          (если забыть — сборка остановится на static_assert в CalendarFace.cpp).
//  Файл простой: только constexpr-константы, никакого кода. Его же читают host-тесты (tests/run.sh).
// ============================================================================
namespace calendar_config {

// ── Погода и сеть ───────────────────────────────────────────────────────────

// Как часто обновлять погоду по Wi-Fi (минуты). Чаще нет смысла: «текущая погода» Open-Meteo считается шагом 15 мин,
// а каждый выход в сеть — расход батареи.
constexpr unsigned kWeatherRefreshMin = 15;
// Как часто перепроверять город по IP (минуты). Сразу же перепроверяется при смене языка интерфейса и при смене
// Wi-Fi-сети (дом ⇄ работа). В режиме «Вручную» (экран «Место») город по IP не запрашивается вовсе.
constexpr unsigned kGeoRefreshMin = 180;

// Данные старше этого считаются устаревшими: значения видны, но с пометкой «устарело · ЧЧ:ММ» (часы).
constexpr unsigned kStaleHours = 3;
// Данные старше этого не показываются вовсе — вместо значений заглушки; город остаётся (часы).
constexpr unsigned kExpireHours = 12;

// Пауза перед первым запросом после входа на экран — чтобы календарь успел нарисоваться (секунды).
constexpr unsigned kFirstRequestDelaySec = 4;
// Сколько ждать подключения к одной Wi-Fi-сети (секунды; для Enterprise — × kWifiEapTimeoutFactor).
constexpr unsigned kWifiConnectTimeoutSec = 15;
// Сколько запомненных сетей пробовать за один выход в сеть: видимые в эфире, от сильного сигнала к слабому.
constexpr unsigned kWifiMaxAttempts = 3;
// Wi-Fi включил кто-то другой, но он не подключён дольше этого (секунды) — считаем его брошенным и берём себе.
// Без этого календарь мог ждать «занятый» Wi-Fi бесконечно.
constexpr unsigned kWifiBusyTakeoverSec = 180;
// Потолок на запросы за один выход в сеть (секунды, от момента подключения к Wi-Fi). Новые запросы после него не
// начинаются (погода — исключение: её запасные пути пробуются до конца). Сеть работает в отдельной задаче, экран и
// кнопки живы.
constexpr unsigned kNetworkBudgetSec = 30;
// Сколько ждать каждого этапа одного запроса (секунды): соединения с сервером (TCP), шифрования (TLS; при неудаче
// клиент прошивки делает вторую попытку — до ×2), первого ответа сервера, очередной порции данных. Прошивка штатно
// ждёт 60 с — из сети, где сервер недоступен, запрос висел минуту.
constexpr unsigned kHttpStageTimeoutSec = 10;
// Сколько ждать соединения с сервером (TCP) и шифрования (TLS), секунды. Обычно это доли секунды; сервер, недоступный
// из вашей сети, не отвечает вовсе — чем меньше, тем быстрее календарь переходит к запасному пути.
constexpr unsigned kHttpConnectTimeoutSec = 5;
// Как представляться серверам. MET Norway и OpenStreetMap требуют название приложения и контакт — иначе блокируют.
constexpr const char* kHttpUserAgent = "CrossMux-Calendar/1.0 (+https://github.com/alexsesser/crossmux-calendar)";

// Запасные пути к погоде (CONCEPT §13.9–13.12). Основной — Open-Meteo по HTTPS. Сервер берётся только по имени
// (api.open-meteo.com) через DNS вашей сети; из части сетей тот сервер, что DNS отдаёт, недоступен (журнал 26.09.2026:
// нет даже TCP-соединения). Не ответил — пробуем по очереди:
//  • тот же сервер обычным HTTP (помогает, если мешают именно шифрованию; если сервер недоступен и по TCP —
//    пропускается). Координаты по HTTP — с точностью ≈ 1 км;
constexpr bool kWeatherHttpFallback = true;
//  • MET Norway (api.met.no, Норвежский метеоинститут, CC BY 4.0) — другой сервер в другой сети. Вероятности
//    осадков у него для России нет (на экране вместо % — мм), остальное — то же.
constexpr bool kWeatherMetNoFallback = true;
// MET Norway пересчитывает прогноз примерно раз в час и просит не спрашивать чаще, чем ответ устаревает (≈ 30 мин):
// погода от него обновляется не чаще этого (минуты).
constexpr unsigned kMetNoMinRefreshMin = 30;
// Путь, который сработал, в следующий раз пробуется первым. Запасной — не дольше этого (минуты), потом снова с начала
// цепочки: Open-Meteo, его другие серверы… Если основной сервер недоступен, такая проверка стоит до ≈ 15 с Wi-Fi.
constexpr unsigned kWeatherPrimaryRetryMin = 60;
// Ниже этого заряда (%) плановые выходы в сеть отпускаются (кнопка Confirm на «Погоде» — в любом случае).
constexpr unsigned kMinBatteryPctForNetwork = 10;
constexpr unsigned kRetryLowBatteryMin = 30;
// Повтор после неудачи: сеть недоступна, сервер не ответил (минуты).
constexpr unsigned kRetryAfterFailMin = 5;
// Повтор, если Wi-Fi занят кем-то другим, например идёт синхронизация времени (секунды).
constexpr unsigned kRetryWifiBusySec = 60;
// Повтор, если в устройстве нет сохранённой Wi-Fi-сети (минуты).
constexpr unsigned kRetryNoWifiMin = 30;

// ── Wi-Fi Enterprise (логин + пароль) ───────────────────────────────────────

// Сети WPA2/WPA3-Enterprise распознаются по скану; для них экран выбора сети спрашивает логин, затем пароль
// (реализация — overlay/src/CalmodWifi.*, хуки — hooks/apply_hooks.py).
// Метод внешней аутентификации: 0 — PEAP/MSCHAPv2 (самый частый в корпоративных сетях), 1 — TTLS.
constexpr int kWifiEapMethod = 0;
// Внешняя («анонимная») идентичность. Пусто — передаётся сам логин. Некоторые сети требуют вида "anonymous@company.ru".
constexpr const char* kWifiEapAnonymousIdentity = "";
// Во сколько раз дольше ждать подключения к Enterprise-сети (рукопожатие TLS медленнее обычного пароля).
constexpr unsigned kWifiEapTimeoutFactor = 3;

// ── Местоположение ──────────────────────────────────────────────────────────
// Режим при первом запуске: true — город по IP (автоматически), false — вручную. Дальше переключается на самом
// устройстве — экран «Место» (тап по названию города на экране «Погода») — и хранится на SD
// (/.crosspoint/calendar_settings.json); эта константа тогда уже не действует.
constexpr bool kLocationAutoByDefault = true;
// Место по умолчанию: начальное значение ручного места (пока вы не выбрали город на экране «Место») и то, что
// показывается в режиме «Авто», пока определить город по IP ни разу не удалось.
// Координаты нужны для погоды и для восхода/заката (градусы: +север, +восток).
constexpr const char* kDefaultCity = "Москва";
constexpr double kDefaultLatitude = 55.7558;
constexpr double kDefaultLongitude = 37.6173;

// ── Диагностика ─────────────────────────────────────────────────────────────
// Подробный журнал на SD-карту: /calendar-logs/ГГГГ-ММ-ДД.log — Wi-Fi (скан, попытки, причины обрыва), запросы,
// геолокация, переходы экранов, заряд, память, плюс все сообщения самой прошивки. Значение при первом запуске;
// дальше включается и выключается на экране «Место» и хранится на SD.
constexpr bool kSdLogByDefault = true;
// Как часто дописывать журнал из памяти на карту (секунды). Реже — меньше записей на SD, но при сбое теряется больше.
constexpr unsigned kSdLogFlushSec = 20;

// ── Праздники и переносы выходных ───────────────────────────────────────────

// Подсвечивать праздники и переносы (как выходные) и подписывать их на экране «День».
constexpr bool kHolidaysEnabled = true;
// Страна производственного календаря (isdayoff.ru: ru, by, kz, ua, us, uz, tr). Переносы и праздники берутся
// из интернета; если данных нет (нет сети / год ещё не опубликован) — для «ru» подсвечиваются фиксированные праздники.
constexpr const char* kHolidayCountry = "ru";
// На сколько лет вперёд (сверх текущего) загружать календарь при выходе в сеть. Год, которого нет в кэше на SD,
// дополнительно запрашивается по требованию, когда вы его открываете (месяц, «День», «Год»).
constexpr unsigned kHolidayPrefetchYears = 5;
// Сколько лет (запросов) загружать за один выход в сеть: каждый запрос — отдельное TLS-соединение (1–2 с).
// Остальное догружается следующими циклами; год, который вы открыли, всегда идёт первым.
// 6 = текущий год + 5 вперёд при первой загрузке одним выходом.
constexpr unsigned kHolidayMaxRequestsPerCycle = 6;
// Как часто перепроверять уже загруженный (и ещё не опубликованный) год (дни): переносы иногда меняют постановлением.
constexpr unsigned kHolidayRefreshDays = 30;

// ── Поведение ───────────────────────────────────────────────────────────────

// ⚠ Календарь — первая грань стендбая (true) или после Sloppy Clock (false). Читает hooks/apply_hooks.py.
constexpr bool kCalendarFirstFace = true;
// Через сколько секунд без ввода возвращаться к текущему месяцу после листания.
constexpr unsigned kMonthAutoReturnSec = 60;
// Каждое N-е минутное обновление экран полностью перерисовывается с «очисткой» (FULL_REFRESH — как кнопка
// «Обновление экрана» в верхнем меню: экран мигнёт). 0 — не чистить по времени (только при смене экранов и в полночь).
constexpr unsigned kGhostCleanupEveryUpdates = 30;

// Вложенные экраны (погода, день, год): закрываются сами через столько секунд без ввода.
constexpr unsigned kDetailAutoCloseSec = 60;
// Пока открыт такой экран, плановое обновление погоды откладывается, пока не пройдёт столько секунд без ввода.
constexpr unsigned kDetailNetworkIdleSec = 10;
// Любой плановый сетевой запрос стартует не раньше, чем через столько мс после последнего ввода — чтобы не
// нагружать Wi-Fi и процессор посреди листания. Так же — для года «по требованию».
constexpr unsigned kOnDemandDebounceMs = 3000;

// ── Раскладка (пиксели) ─────────────────────────────────────────────────────

// Поля слева/справа в портрете.
constexpr int kSidePad = 24;
// Поля левой колонки в ландшафте (там места меньше).
constexpr int kLandscapePad = 14;
// Ширина левой колонки в ландшафте, % от ширины экрана. Остальное — сетка месяца.
constexpr int kLandscapeLeftPct = 41;
// Высота строки сетки месяца: не больше / не меньше. Реальная считается по свободному месту.
constexpr int kMaxRowH = 80;
constexpr int kMinRowH = 34;
// Отступ сверху и снизу под оверлей активности (заголовок, батарея, точки-пейджер). Менять осторожно:
// значения должны оставлять место элементам, которые рисует StandbyActivity.
constexpr int kTopReserve = 34;
constexpr int kBottomReserve = 44;

// ── ⚠ Размеры шрифта крупных цифр (pt @150 dpi; высота цифры ≈ 1.5 × pt px) ────────────────────
// Читает tools/gen_digit_fonts.sh. Портрет: время должно помещаться по ширине экрана (~3.7 × высота цифры).
constexpr int kTimeFontPortraitPt = 70;
constexpr int kTimeFontLandscapePt = 50;
constexpr int kTempFontPt = 25;
// Числа в сетке месяца (только цифры). Крупнее стандартного 12 pt интерфейса — сетка читается издалека.
constexpr int kDayFontPt = 17;
// ⚠ Числа текущего месяца в сетке: true — жирнее (Ubuntu Medium), false — обычные (Ubuntu Regular). Читает генератор шрифта.
constexpr bool kGridDigitsBold = false;

}  // namespace calendar_config
